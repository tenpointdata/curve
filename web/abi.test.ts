// The JavaScript ABI of a checked module: one book yields a guarded .mjs and
// its .d.mts; these tests check the declarations under strict tsc, the guard
// at runtime, the derivation errors, and that vite can bundle the module.
import { beforeAll, describe, expect, test } from "bun:test";
import { existsSync, mkdtempSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const cli = join(import.meta.dir, "../curve2/main.ts");
const tscJs = join(import.meta.dir, "node_modules/typescript/bin/tsc");
const decoder = new TextDecoder();
const SLOW = 120_000;

type Run = { code: number; out: string; err: string };
type Fn = (...a: readonly unknown[]) => unknown;
type Mod = Readonly<Record<string, Fn>>;

function scratch(): string {
  return mkdtempSync(join(tmpdir(), "curve-abi-test-"));
}

function put(dir: string, files: Readonly<Record<string, string>>): void {
  for (const [name, text] of Object.entries(files)) {
    writeFileSync(join(dir, name), text);
  }
}

function spawn(cmd: string[], cwd: string): Run {
  const r = Bun.spawnSync(cmd, { cwd, timeout: 90_000,
    env: { ...process.env, CURVE_NO_TELEMETRY: "1" } });
  return { code: r.exitCode ?? -1, out: decoder.decode(r.stdout), err: decoder.decode(r.stderr) };
}

// emit writes <stem>.mjs and <stem>.d.mts next to the source.
function emit(dir: string, src: string, stem: string, args: string[]): Run {
  return spawn([process.execPath, cli, src, "-o", stem + ".mjs", "-o", stem + ".d.mts", ...args], dir);
}

function isMod(v: unknown): v is Mod {
  return typeof v === "object" && v !== null && Object.values(v).every((f) => typeof f === "function");
}

async function load(file: string): Promise<Mod> {
  const m: unknown = (await import(pathToFileURL(file).href)).default;
  if (!isMod(m)) {
    throw new Error("Expected a module of functions: " + file);
  }
  return m;
}

function call(m: Mod, key: string, ...a: unknown[]): unknown {
  const f = m[key];
  if (f === undefined) {
    throw new Error("No export " + key);
  }
  return f(...a);
}

