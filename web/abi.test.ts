describe("derivation errors", () => {
  const CASES: ReadonlyArray<{ name: string; src: string; args: string[]; message: string }> = [
    { name: "a polymorphic export", message: "ABI of export poly",
      src: "import Base\ndef poly(-A: Type, x: A) -> A:\n  x\n", args: ["--export", "poly"] },
    { name: "a function inside a datatype field", message: "ABI of",
      src: "import Base\ntype Box is Type:\n  Box{f: U32 -> U32}\n"
        + "def box(f: U32 -> U32) -> Box:\n  Box{f}\n", args: ["--export", "box"] },
    { name: "a --type naming an unused type", message: "--type",
      src: "import Base\ntype Color is Data:\n  Red{}\n  Blue{}\n"
        + "def one(n: U32) -> U32:\n  n\n", args: ["--export", "one", "--type", "Color=Hue"] },
    { name: "a --type that is not an identifier", message: "not a TypeScript identifier",
      src: "import Base\ntype Color is Data:\n  Red{}\n  Blue{}\n"
        + "def pick(c: Color) -> Color:\n  c\n", args: ["--export", "pick", "--type", "Color=1x"] },
  ];

  for (const c of CASES) {
    test(c.name + " exits 1 and writes nothing", () => {
      const d = scratch();
      put(d, { "bad.curve": c.src });
      const r = emit(d, "bad.curve", "bad", c.args);
      expect(r.code).toBe(1);
      expect(r.err).toContain(c.message);
      expect(existsSync(join(d, "bad.mjs"))).toBe(false);
      expect(existsSync(join(d, "bad.d.mts"))).toBe(false);
    }, SLOW);
  }

  test("--type without a .d.mts output is refused", () => {
    const d = scratch();
    put(d, { "ok.curve": "import Base\ndef one(n: U32) -> U32:\n  n\n" });
    const r = spawn([process.execPath, cli, "ok.curve", "-o", "ok.mjs", "--type", "A=B"], d);
    expect(r.code).toBe(1);
    expect(r.err).toContain("--type requires a .d.mts output");
    expect(existsSync(join(d, "ok.mjs"))).toBe(false);
  }, SLOW);
});

