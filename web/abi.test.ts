// 3. Runtime boundary checks
// ==========================

function rejects(key: string, arg: string, ...values: unknown[]): void {
  for (const v of values) {
    expect(() => call(mod, key, v)).toThrow(TypeError);
    expect(() => call(mod, key, v)).toThrow("curve abi: " + key + " argument " + arg);
  }
}

describe("boundary", () => {
  test("Nat is a safe non-negative integer", () => {
    expect(call(mod, "nat_id", 0)).toBe(0);
    expect(call(mod, "nat_id", 2 ** 53 - 1)).toBe(2 ** 53 - 1);
    rejects("nat_id", "n", -1, 1.5, 2 ** 53, Number.NaN, "1", 1n);
  });

  test("U32 is an integer in 0..2^32-1", () => {
    expect(call(mod, "u32_id", 0)).toBe(0);
    expect(call(mod, "u32_id", 4294967295)).toBe(4294967295);
    rejects("u32_id", "n", 4294967296, -1);
  });

  test("F32 is exactly a float32, NaN and infinities included", () => {
    expect(call(mod, "f32_id", 0.5)).toBe(0.5);
    expect(call(mod, "f32_id", Number.NaN)).toBeNaN();
    expect(call(mod, "f32_id", Number.POSITIVE_INFINITY)).toBe(Number.POSITIVE_INFINITY);
    rejects("f32_id", "n", 0.1);
  });

  test("Bool is a boolean and nothing truthy", () => {
    expect(call(mod, "bool_id", true)).toBe(true);
    expect(call(mod, "bool_id", false)).toBe(false);
    rejects("bool_id", "b", 0, 1, "true");
  });

  test("String round-trips Unicode and refuses lone surrogates", () => {
    for (const s of ["", "héllo", "👋🏽", "𝄞"]) {
      expect(call(mod, "str_id", s)).toBe(s);
    }
    rejects("str_id", "s", "\uD800", "a\uDC00b");
  });

  test("Char is exactly one code point", () => {
    expect(call(mod, "char_id", "a")).toBe("a");
    expect(call(mod, "char_id", "𝄞")).toBe("𝄞");
    rejects("char_id", "c", "ab", "", "\uD800");
  });

  test("Array length is a power of two", () => {
    expect(call(mod, "arr_id", [1, 2, 3, 4])).toEqual([1, 2, 3, 4]);
    rejects("arr_id", "a", [1, 2, 3], [], "ab");
    expect(() => call(mod, "arr_id", [1, 2, 3, 4, 5, 6, 7, -1])).toThrow("argument a[7]");
  });

  test("datatypes refuse extra keys, missing fields and unknown tags, naming the path", () => {
    const ok = { $: "Rect", w: 1, h: 2 };
    expect(call(mod, "shape_id", ok)).toEqual(ok);
    expect(call(mod, "color_id", { $: "Green" })).toEqual({ $: "Green" });
    expect(() => call(mod, "shape_id", { $: "Dot", extra: 1 })).toThrow('Dot has no field "extra"');
    expect(() => call(mod, "shape_id", { $: "Rect", w: 1 })).toThrow('Rect is missing field "h"');
    expect(() => call(mod, "shape_id", { $: "Rect", w: 1, z: 2 })).toThrow('Rect has no field "z" and is missing field "h"');
    expect(() => call(mod, "shape_id", { $: "Tri" })).toThrow('expected {$: "Circle" | "Rect" | "Dot"}, got {$: "Tri"}');
    expect(() => call(mod, "shape_id", { w: 1 })).toThrow("argument s");
    expect(() => call(mod, "shape_id", null)).toThrow(TypeError);
    expect(() => call(mod, "shape_id", { $: "Circle", r: -1 })).toThrow("argument s.r: expected a U32");
  });

  test("Maybe and List validate their parameter at every depth", () => {
    expect(call(mod, "maybe_id", { $: "Some", value: 7 })).toEqual({ $: "Some", value: 7 });
    expect(() => call(mod, "maybe_id", { $: "Some", value: "7" })).toThrow("argument m.value");
    const xs = { $: "Con", head: "a", tail: { $: "Con", head: "b", tail: { $: "Nil" } } };
    expect(call(mod, "list_id", xs)).toEqual(xs);
    const bad = { $: "Con", head: "a", tail: { $: "Con", head: 3, tail: { $: "Nil" } } };
    expect(() => call(mod, "list_id", bad)).toThrow("argument m.tail.head: expected a well-formed string");
  });

  test("a long List is checked without recursion", () => {
    let xs: unknown = { $: "Nil" };
    for (let i = 0; i < 200_000; i++) {
      xs = { $: "Con", head: "x", tail: xs };
    }
    expect(() => call(mod, "list_id", xs)).not.toThrow(RangeError);
  });

  test("wrong arity is refused, not curried", () => {
    expect(() => call(mod, "nat_id")).toThrow("nat_id takes 1 argument(s), got 0");
    expect(() => call(mod, "nat_id", 1, 2)).toThrow("takes 1 argument(s), got 2");
    expect(() => call(mod, "apply", (a: number) => (b: number) => a + b, 1)).toThrow("takes 3 argument(s), got 2");
  });

  test("the module object is frozen", () => {
    expect(Object.isFrozen(mod)).toBe(true);
  });
});

// 4. Callback reach
// =================

describe("callbacks", () => {
  test("b is only called when a returns False; each is called once", () => {
    const count = { a: 0, b: 0 };
    const probe = (side: "a" | "b", v: boolean) => (): boolean => {
      count[side] += 1;
      return v;
    };
    expect(call(mod, "select", probe("a", true), probe("b", true))).toEqual({ $: "Allow" });
    expect(count).toEqual({ a: 1, b: 0 });
    expect(call(mod, "select", probe("a", false), probe("b", true))).toEqual({ $: "Allow" });
    expect(count).toEqual({ a: 2, b: 1 });
    expect(call(mod, "select", probe("a", false), probe("b", false))).toEqual({ $: "Deny", reason: "no" });
    expect(count).toEqual({ a: 3, b: 2 });
  });

  test("a callback receives a Unit value and may not return a non-boolean", () => {
    const seen: unknown[] = [];
    call(mod, "select", (u: unknown) => {
      seen.push(u);
      return true;
    }, () => true);
    expect(seen).toEqual([{ $: "Unit" }]);
    expect(() => call(mod, "select", () => 1, () => true)).toThrow(TypeError);
    expect(() => call(mod, "select", () => 1, () => true)).toThrow("select argument a result: expected a boolean");
    expect(() => call(mod, "select", () => false, () => "yes")).toThrow("select argument b result");
  });

  test("a callback that throws propagates its own error", () => {
    expect(() => call(mod, "select", () => {
      throw new RangeError("boom");
    }, () => true)).toThrow(RangeError);
  });

  test("a non-function where a callback belongs is refused", () => {
    expect(() => call(mod, "select", true, () => true)).toThrow("select argument a: expected a function, got true");
  });

  test("a curried callback is checked at both arguments and the result", () => {
    expect(call(mod, "apply", (a: number) => (b: number) => a + b, 40, 2)).toBe(42);
    expect(() => call(mod, "apply", (a: number) => a, 1, 2)).toThrow("apply argument f result: expected a function");
    expect(() => call(mod, "apply", (a: number) => (b: number) => `${a}${b}`, 1, 2))
      .toThrow("apply argument f result result: expected a U32");
  });

  test("a returned closure validates its argument and result", () => {
    const add = call(mod, "partial", 40);
    if (typeof add !== "function") {
      throw new Error("Expected a closure");
    }
    expect(() => add("2")).toThrow("partial result argument: expected a U32");
    expect(() => add(1, 2)).toThrow("takes 1 argument, got 2");
    expect(() => add(-1)).toThrow(TypeError);
    expect(add(2)).toBe(42);
  });
});

